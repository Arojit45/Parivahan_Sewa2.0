const langs = ['hi', 'bn', 'mr', 'ta', 'te', 'kn', 'ml', 'gu', 'pa', 'or'];

langs.forEach(lang => {
  const filePath = path.join(translationsPath, `${lang}.js`);
  let content = fs.readFileSync(filePath, 'utf8');
  
  if (content.includes('vr: {') || content.includes('vr : {')) {
    console.log(`Skipping ${lang}.js as it already contains 'vr' object.`);
    return;
  }
  
  // Find the end of the object
  const lastBraceIndex = content.lastIndexOf('}');
  if (lastBraceIndex !== -1) {
    const translationStr = JSON.stringify(translations[lang], null, 4).replace(/"([^"]+)":/g, '$1:');
    content = content.substring(0, lastBraceIndex - 1) + ',\n  vr: ' + translationStr + '\n};\n';
    fs.writeFileSync(filePath, content, 'utf8');
    console.log(`Updated ${lang}.js successfully.`);
  }
});
